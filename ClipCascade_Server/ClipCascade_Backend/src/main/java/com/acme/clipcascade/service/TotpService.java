package com.acme.clipcascade.service;

import java.util.HashMap;
import java.util.Locale;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

import org.springframework.stereotype.Service;

import com.acme.clipcascade.config.ClipCascadeProperties;
import com.acme.clipcascade.model.TotpSecret;
import com.acme.clipcascade.repo.TotpSecretRepo;
import com.acme.clipcascade.utils.TimeUtility;
import com.acme.clipcascade.utils.TotpUtility;
import com.acme.clipcascade.utils.UserValidator;

@Service
public class TotpService {

    private final TotpSecretRepo totpSecretRepo;
    private final ClipCascadeProperties clipCascadeProperties;

    // Secrets generated by /totp/setup but not yet confirmed with a valid code.
    // Kept in memory only: a restart simply requires running setup again.
    private final Map<String, String> pendingSecrets = new ConcurrentHashMap<>();

    public TotpService(
            TotpSecretRepo totpSecretRepo,
            ClipCascadeProperties clipCascadeProperties) {

        this.totpSecretRepo = totpSecretRepo;
        this.clipCascadeProperties = clipCascadeProperties;
    }

    public boolean isServerEnabled() {
        return clipCascadeProperties.isTotpEnabled();
    }

    public boolean isEnabled(String username) {
        if (!isServerEnabled() || !UserValidator.isValidUsername(username)) {
            return false;
        }
        TotpSecret row = totpSecretRepo.findByUsernameIgnoreCase(username);
        return row != null && row.isEnabled() && row.getSecret() != null && !row.getSecret().isBlank();
    }

    public boolean hasPendingSecret(String username) {
        return UserValidator.isValidUsername(username)
                && pendingSecrets.containsKey(pendingKey(username));
    }

    public Map<String, String> startSetup(String username) {
        if (!isServerEnabled() || !UserValidator.isValidUsername(username)) {
            return null;
        }

        String secret = TotpUtility.generateSecret();
        pendingSecrets.put(pendingKey(username), secret);

        Map<String, String> result = new HashMap<>();
        result.put("secret", secret);
        result.put("uri", TotpUtility.buildOtpAuthUri(
                clipCascadeProperties.getTotpIssuer(),
                username,
                secret));
        return result;
    }

    public boolean confirmSetup(String username, String code) {
        if (!isServerEnabled() || !UserValidator.isValidUsername(username)
                || !UserValidator.isValidTotpCode(code)) {
            return false;
        }

        String pending = pendingSecrets.get(pendingKey(username));
        if (pending == null || !TotpUtility.verifyCode(pending, code.trim())) {
            return false;
        }

        TotpSecret row = totpSecretRepo.findById(username).orElseGet(TotpSecret::new);
        row.setUsername(username);
        row.setSecret(pending);
        row.setEnabled(true);
        row.setCreatedAt(TimeUtility.getCurrentTimeInSeconds());
        totpSecretRepo.save(row);

        pendingSecrets.remove(pendingKey(username));
        return true;
    }

    public boolean disable(String username, String code) {
        if (!UserValidator.isValidUsername(username) || !UserValidator.isValidTotpCode(code)) {
            return false;
        }

        TotpSecret row = totpSecretRepo.findByUsernameIgnoreCase(username);
        if (row == null || !row.isEnabled() || row.getSecret() == null
                || !TotpUtility.verifyCode(row.getSecret(), code.trim())) {
            return false;
        }

        totpSecretRepo.delete(row);
        pendingSecrets.remove(pendingKey(username));
        return true;
    }

    public boolean verifyLoginCode(String username, String code) {
        if (!UserValidator.isValidUsername(username) || !UserValidator.isValidTotpCode(code)) {
            return false;
        }

        TotpSecret row = totpSecretRepo.findByUsernameIgnoreCase(username);
        if (row == null || !row.isEnabled() || row.getSecret() == null) {
            return false;
        }

        return TotpUtility.verifyCode(row.getSecret(), code.trim());
    }

    public void clear(String username) {
        if (!UserValidator.isValidUsername(username)) {
            return;
        }
        totpSecretRepo.findByUsernameIgnoreCase(username)
                .ifPresent(totpSecretRepo::delete);
        pendingSecrets.remove(pendingKey(username));
    }

    public void rename(String oldUsername, String newUsername) {
        if (!UserValidator.isValidUsername(oldUsername)
                || !UserValidator.isValidUsername(newUsername)) {
            return;
        }
        TotpSecret row = totpSecretRepo.findByUsernameIgnoreCase(oldUsername);
        if (row == null) {
            return;
        }
        totpSecretRepo.delete(row);
        row.setUsername(newUsername);
        totpSecretRepo.save(row);
        pendingSecrets.remove(pendingKey(oldUsername));
    }

    private static String pendingKey(String username) {
        return username.toLowerCase(Locale.ROOT);
    }
}
